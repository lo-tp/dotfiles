herdr pane run "$PANE2_1" 'export GOPATH=$HOME/go' >/dev/null
herdr pane run "$PANE2_1" 'export PATH=$PATH:$GOPATH/bin' >/dev/null
herdr pane run "$PANE2_1" 'source .venv/bin/activate' >/dev/null
herdr pane run "$PANE2_1" 'scripts/generate_openapi.py singleorigin-api' >/dev/null

pane2_2_json="$(herdr pane split "$PANE2_1" --direction right --ratio "$SPLIT_RATIO" --cwd "$ROOT" --no-focus)"
PANE2_2="$(jget '.result.pane.pane_id' "$pane2_2_json")"

herdr pane rename "$PANE2_2" 'cmd 1' >/dev/null
herdr pane run "$PANE2_2" 'export SESSION_HOME="~/.config/nvim/session/single-origin"' >/dev/null
herdr pane run "$PANE2_2" 'cd proto/singleorigin-api' >/dev/null
herdr pane run "$PANE2_2" 'buf lint' >/dev/null

# ------------------- window 3: Helm Editor --------------------
