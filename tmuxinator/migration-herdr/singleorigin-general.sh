#   windows: 1 Proto Editor(single: Proto Editor) | 2 Proto CMD(main-vertical: cmd 0|cmd 1) | 3 Helm Editor(single: Helm Editor) | 4 Helm CMD(single: Helm CMD) | 5 Terraform Editor(single: Terraform Editor) | 6 Terraform CMD(main-vertical: cmd 0|cmd 1) | 7 Airflow Editor(single: Airflow Editor) | 8 Airflow CMD(main-vertical: cmd 0|cmd 1) | 9 Bootstrap Editor(single: Bootstrap Editor) | 10 Bootstrap CMD(single: Bootstrap CMD)
