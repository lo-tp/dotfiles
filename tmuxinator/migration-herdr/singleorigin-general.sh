WS_ID="$(jget '.result.workspace.workspace_id' "$ws_json")"
TAB1_ID="$(jget '.result.tab.tab_id' "$ws_json")"
PANE1_1="$(jget '.result.root_pane.pane_id' "$ws_json")"

name_tab "$TAB1_ID" 'Proto Editor'

herdr pane rename "$PANE1_1" 'Proto Editor' >/dev/null
herdr pane run "$PANE1_1" 'export SESSION_HOME="~/.config/nvim/session/single-origin"' >/dev/null
herdr pane run "$PANE1_1" 'cd proto' >/dev/null
herdr pane run "$PANE1_1" 'export VIM_SESSION=$SESSION_HOME/proto.vim' >/dev/null

# ------------------- window 2: Proto CMD --------------------
