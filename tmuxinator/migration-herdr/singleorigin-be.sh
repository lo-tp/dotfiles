herdr pane run "$PANE1_1" 'export PATH=%JAVA_HOME/bin:$PATH' >/dev/null
herdr pane run "$PANE1_1" 'export SESSION_HOME="~/.config/nvim/session/single-origin"' >/dev/null
herdr pane run "$PANE1_1" 'export DOCKER_BUILDKIT=0' >/dev/null
herdr pane run "$PANE1_1" 'export COMPOSE_PROFILES=infra,core' >/dev/null
herdr pane run "$PANE1_1" 'cd core' >/dev/null
herdr pane run "$PANE1_1" 'export VIM_SESSION=$SESSION_HOME/api-core.vim' >/dev/null

# ------------------- window 2: API CMD --------------------
